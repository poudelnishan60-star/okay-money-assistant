"""Export the BS (Bikram Sambat) calendar from the backend's nepali-datetime package to Dart,
so the app and the backend agree on every BS date.

Why: the Flutter package nepali_utils 3.0.8 converts AD -> BS one day late (e.g. 9 Nov 2026
-> Kartik 24 instead of 23) and its 2084 BS table differs from the published calendar
(Jestha 2084 has 31 days, not 32). nepali-datetime matches the published calendar for both.

    python scripts/export_bs_calendar.py

Writes app/lib/features/ai_assistant/core/bs_calendar_data.dart and
app/test/ai_assistant/fixtures/bs_samples.json (sample AD/BS pairs for a parity test).
"""

from __future__ import annotations

import datetime as dt
import json
from pathlib import Path

import nepali_datetime as nd

FIRST_YEAR = 2000  # BS 2000 starts in April 1943
LAST_YEAR = 2099  # BS 2099 ends in April 2043

REPO = Path(__file__).resolve().parents[2]
DART_OUT = REPO / "app/lib/features/ai_assistant/core/bs_calendar_data.dart"
FIXTURE_OUT = REPO / "app/test/ai_assistant/fixtures/bs_samples.json"


def month_lengths(year: int) -> list[int]:
    lengths = []
    for m in range(1, 13):
        start = nd.date(year, m, 1).to_datetime_date()
        nxt = nd.date(year + 1, 1, 1) if m == 12 else nd.date(year, m + 1, 1)
        lengths.append((nxt.to_datetime_date() - start).days)
    return lengths


def main() -> None:
    first_ad = nd.date(FIRST_YEAR, 1, 1).to_datetime_date()
    rows = [f"  {y}: {month_lengths(y)}," for y in range(FIRST_YEAR, LAST_YEAR + 1)]
    names_en = list(nd._FULLMONTHNAMES[1:])  # noqa: SLF001
    names_np = list(nd._MONTHNAMES_NP[1:])  # noqa: SLF001
    dart = "\n".join(
        [
            "// GENERATED by backend/scripts/export_bs_calendar.py from nepali-datetime "
            f"{getattr(nd, '__version__', '')}. Do not edit.",
            "// ignore_for_file: prefer_single_quotes, require_trailing_commas",
            "",
            f"const int bsFirstYear = {FIRST_YEAR};",
            f"const int bsLastYear = {LAST_YEAR};",
            "",
            f"/// AD date of 1 Baishakh {FIRST_YEAR} BS.",
            f"final DateTime bsEpochAd = DateTime.utc({first_ad.year}, {first_ad.month}, "
            f"{first_ad.day});",
            "",
            "/// Days in each BS month, Baishakh..Chaitra.",
            "const Map<int, List<int>> bsMonthLengths = {",
            *rows,
            "};",
            "",
            f"const List<String> bsMonthNames = {json.dumps(names_en)};",
            f"const List<String> bsMonthNamesNepali = {json.dumps(names_np, ensure_ascii=False)};",
            "",
        ]
    )
    DART_OUT.write_text(dart, encoding="utf-8")

    # Every 5th day from 2010 to 2040 AD, plus month starts around today.
    samples = []
    day = dt.date(2010, 1, 1)
    while day <= dt.date(2040, 12, 31):
        bs = nd.date.from_datetime_date(day)
        samples.append([day.isoformat(), bs.year, bs.month, bs.day])
        day += dt.timedelta(days=5)
    for y in range(2080, 2086):
        for m in range(1, 13):
            ad = nd.date(y, m, 1).to_datetime_date()
            samples.append([ad.isoformat(), y, m, 1])
    FIXTURE_OUT.parent.mkdir(parents=True, exist_ok=True)
    FIXTURE_OUT.write_text(json.dumps(samples), encoding="utf-8")
    print(f"wrote {DART_OUT.relative_to(REPO)} and {len(samples)} samples")  # noqa: T201


if __name__ == "__main__":
    main()
